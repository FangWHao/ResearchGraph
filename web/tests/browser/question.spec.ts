test('旧成功响应延迟到达时保留切换项目后的新草稿，正确保存新意图', async ({ page, request }) => {
  const bodies: QuestionRequest[] = [];
  const oldSaved: QuestionResult[] = [];
  let release!: () => void;
  const held = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/records/question', async route => {
    bodies.push(route.request().postDataJSON());
    const response = await route.fetch();
    if (bodies.length === 1) { oldSaved.push(await response.json()); await held; }
    await route.fulfill({ response });
  });
  let dialog = await openQuestion(page);
  const oldText = '合成延迟响应的旧人工问题';
  const newText = '合成切回项目后输入的新人工问题';
  const otherText = '合成另一项目尚未提交的草稿';
  await dialog.getByLabel('研究问题正文', { exact: true }).fill(oldText);
  const oldResponse = page.waitForResponse(response => response.url().endsWith('/api/records/question'));
  await dialog.getByRole('button', { name: '保存研究问题', exact: true }).click();
  await expect.poll(() => oldSaved.length).toBe(1);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await page.getByLabel('当前项目', { exact: true }).selectOption({ label: secondary });
  await page.getByRole('button', { name: '新增研究问题', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '新增研究问题', exact: true });
  await dialog.getByLabel('研究问题正文', { exact: true }).fill(otherText);
  await dialog.getByRole('button', { name: '关闭新增问题', exact: true }).click();
  await page.getByLabel('当前项目', { exact: true }).selectOption({ label: primary });
  await page.getByRole('button', { name: '新增研究问题', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '新增研究问题', exact: true });
  await dialog.getByLabel('研究问题正文', { exact: true }).fill(newText);
  release();
  expect((await oldResponse).status()).toBe(200);
  await expect(dialog.getByLabel('研究问题正文', { exact: true })).toHaveValue(newText);
  await expect(dialog.getByRole('button', { name: '保存研究问题', exact: true })).toBeEnabled();
  await expect(page.getByRole('dialog', { name: `记录 ${oldSaved[0].claim_id} 详情`, exact: true })).toHaveCount(0);
  const savedResponse = page.waitForResponse(response => response.url().endsWith('/api/records/question'));
  await dialog.getByRole('button', { name: '保存研究问题', exact: true }).click();
  const saved: QuestionResult = await (await savedResponse).json();
  expect(bodies).toHaveLength(2);
  expect(bodies[1].request_id).not.toBe(bodies[0].request_id);
  expect(bodies[1].project_id).toBe(bodies[0].project_id);
  await expect(page.getByRole('dialog', { name: `记录 ${saved.claim_id} 详情`, exact: true })).toContainText(newText);
  const graph: GraphData = await (await request.get(`/api/graph?project=${bodies[0].project_id}`, { headers })).json();
  expect(graph.claims.filter(item => item.payload.content === oldText)).toHaveLength(1);
  expect(graph.claims.filter(item => item.payload.content === newText)).toHaveLength(1);
  await page.getByRole('button', { name: '关闭详情', exact: true }).click();
  await page.getByLabel('当前项目', { exact: true }).selectOption({ label: secondary });
  await page.getByRole('button', { name: '新增研究问题', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '新增研究问题', exact: true }).getByLabel('研究问题正文', { exact: true })).toHaveValue(otherText);
});
